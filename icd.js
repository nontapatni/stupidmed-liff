function suggestICD(dx) {
    // ขยายคำย่อที่ใช้บ่อยก่อนจับคู่
    const s = String(dx || "").replace(/\bfx\b/gi, "fracture").replace(/\bca\.\s*/gi, "ca ").replace(/\bs\/p\b/gi, "status post");
    if (!s.trim()) return [];
    const out = [];
    for (const [re, code, label] of ICD_HINTS) if (re.test(s) && !out.some(o => o.code === code)) out.push({ code, label });
    return out.slice(0, 5);
  }
function icdToGroup(code) {
    const m = String(code || "").toUpperCase().trim().match(/^([A-Z])(\d{2})/);
    if (!m) return "";
    const L = m[1], n = +m[2];
    if (L === "A" || L === "B") return "01";
    if (L === "C" || (L === "D" && n <= 48)) return "02";
    if (L === "D") return "03";
    const simple = { E: "04", F: "05", G: "06", I: "09", J: "10", K: "11", L: "12", M: "13", N: "14", O: "15", P: "16", Q: "17", S: "18", T: "18" };
    if (L === "H") return n <= 59 ? "07" : "08";
    if (simple[L]) return simple[L];
    if ("VWXY".includes(L)) return "19";
    return "";
  }
